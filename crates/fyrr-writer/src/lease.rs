//! Namespace coordination through the existing head lease and conditional writes.

use crate::telemetry::{self, HeadWriteStage};
use crate::{Result, WriterError};
use chrono::{DateTime, Utc};
use fyrr_core::config::Config;
use fyrr_core::limits::digest;
use fyrr_core::publication::{Lease, ServingHead};
use fyrr_core::{Contract, parse_contract, write_contract};
use fyrr_reader::storage::namespace_store;
use object_store::path::Path;
use object_store::{ObjectMeta, ObjectStore, ObjectStoreExt, PutMode, PutOptions, UpdateVersion};
use std::sync::Arc;
use std::time::{Duration, Instant};
use tokio::sync::Mutex;

/// Stop between renewals, never by cancelling a conditional write whose
/// response may be lost after the store has already committed it.
pub(crate) struct Renewal {
    stop: tokio::sync::oneshot::Sender<()>,
    task: tokio::task::JoinHandle<()>,
}

impl Renewal {
    pub(crate) fn spawn<F, Fut>(interval: Duration, mut renew: F) -> Self
    where
        F: FnMut() -> Fut + Send + 'static,
        Fut: std::future::Future<Output = bool> + Send,
    {
        let (stop, mut stopping) = tokio::sync::oneshot::channel();
        let task = tokio::spawn(async move {
            loop {
                tokio::select! {
                    biased;
                    _ = &mut stopping => break,
                    () = tokio::time::sleep(interval) => {}
                }
                if !renew().await {
                    break;
                }
            }
        });
        Self { stop, task }
    }

    pub(crate) async fn stop(self) -> Result<()> {
        let _ = self.stop.send(());
        self.task.await.map_err(|_| WriterError::RuntimeUnavailable)
    }
}

pub(crate) fn new_lease(
    previous: Option<&Lease>,
    now: DateTime<Utc>,
    ttl: Duration,
    seed: &[u8],
) -> Result<Lease> {
    Ok(Lease {
        holder: format!("holder-{}", &digest(seed)[7..39]),
        epoch: previous.map_or(Ok(1), |lease| {
            lease
                .epoch
                .checked_add(1)
                .ok_or(WriterError::LeaseEpochOverflow)
        })?,
        expires_at: now + chrono::Duration::from_std(ttl).map_err(|_| WriterError::LeaseInvalid)?,
    })
}

pub(crate) fn version_of(meta: &ObjectMeta) -> UpdateVersion {
    UpdateVersion {
        e_tag: meta.e_tag.clone(),
        version: meta.version.clone(),
    }
}

pub(crate) async fn cas_put<T: Contract>(
    store: &dyn ObjectStore,
    path: &Path,
    document: &T,
    mode: PutMode,
) -> Result<UpdateVersion, object_store::Error> {
    store
        .put_opts(
            path,
            write_contract(document).into(),
            PutOptions {
                mode,
                ..Default::default()
            },
        )
        .await
        .map(Into::into)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum HeadStatus {
    Live,
    Failed,
    Deleted,
}

#[derive(Debug)]
struct HeldHead {
    head: ServingHead,
    expected: UpdateVersion,
    renewed: Instant,
    status: HeadStatus,
}

/// A process-local handle to the S3 authority, not another durable state store.
#[derive(Debug)]
pub struct LeaseGuard {
    store: Arc<dyn ObjectStore>,
    path: Path,
    lease: Lease,
    ttl: Duration,
    state: Mutex<HeldHead>,
    observed: fyrr_reader::storage::ObservedDurability,
}

impl LeaseGuard {
    pub async fn with<T, E, F, Fut>(config: &Config, body: F) -> Result<T, E>
    where
        E: From<WriterError>,
        F: FnOnce(Arc<Self>) -> Fut,
        Fut: std::future::Future<Output = Result<T, E>>,
    {
        let lease = Self::acquire(config).await.map_err(E::from)?;
        let keepalive = lease.keepalive();
        let result = body(lease.clone()).await;
        let release = match keepalive.stop().await {
            Ok(()) => lease.release().await,
            Err(error) => Err(error),
        };
        if result.is_ok() {
            release.map_err(E::from)?;
        }
        result
    }

    #[allow(clippy::print_stderr)]
    pub async fn acquire(config: &Config) -> Result<Arc<Self>> {
        let (store, root) = namespace_store(config)?;
        let path = root.join("head.json");
        let object = store.get(&path).await?;
        let expected = version_of(&object.meta);
        let mut head: ServingHead =
            parse_contract(&object.bytes().await?).map_err(|_| WriterError::PublicationInvalid)?;
        if head.namespace != config.namespace.name {
            return Err(WriterError::PublicationNamespaceInvalid);
        }
        let now = fyrr_core::clock::now();
        if let Some(lease) = &head.lease
            && lease.expires_at > now
        {
            // The holder is generated by fyrr; reject external values before logging.
            if lease
                .holder
                .strip_prefix("holder-")
                .is_some_and(|value| fyrr_core::limits::ascii_hex(value, 32))
            {
                eprintln!(
                    "writer_busy holder={} expires_at={}",
                    lease.holder, lease.expires_at
                );
            }
            return Err(WriterError::CommitterBusy);
        }
        let ttl = config.writer.commit.lease_ttl.as_duration();
        let lease = new_lease(
            head.lease.as_ref(),
            now,
            ttl,
            format!("{}:{}:{now:?}", config.namespace.name, std::process::id()).as_bytes(),
        )?;
        head.lease = Some(lease.clone());
        head.schema_version = fyrr_core::publication::PUBLICATION_CONTRACT_VERSION;
        let result = cas_put(store.as_ref(), &path, &head, PutMode::Update(expected))
            .await
            .map_err(|error| match error {
                object_store::Error::Precondition { .. } => WriterError::CommitterBusy,
                _ => WriterError::StorageUnavailable,
            })?;
        Ok(Arc::new(Self {
            observed: fyrr_reader::storage::observed_durability(config)?,
            store,
            path,
            lease,
            ttl,
            state: Mutex::new(HeldHead {
                head,
                expected: result,
                renewed: Instant::now(),
                status: HeadStatus::Live,
            }),
        }))
    }

    pub fn holder(&self) -> &Lease {
        &self.lease
    }

    fn live(&self, state: &HeldHead) -> Result<()> {
        if state.status != HeadStatus::Live
            || state.renewed.elapsed() >= self.ttl
            || state
                .head
                .lease
                .as_ref()
                .is_none_or(|l| l.expires_at <= fyrr_core::clock::now())
        {
            return Err(WriterError::LeaseLost);
        }
        Ok(())
    }

    pub async fn head(&self) -> Result<ServingHead> {
        let state = self.state.lock().await;
        self.live(&state)?;
        Ok(state.head.clone())
    }

    /// Renewals and publication share one CAS token, serialized only in this holder.
    pub async fn publish(&self, mut head: ServingHead) -> Result<()> {
        let mut state = self.state.lock().await;
        self.live(&state)?;
        head.lease = state.head.lease.clone();
        head.schema_version = fyrr_core::publication::PUBLICATION_CONTRACT_VERSION;
        // The head makes its manifest, policy and identity objects, the
        // envelopes and rejections they record, and everything those were
        // derived from reachable. Other processes wrote some of them.
        self.observed.persist().await?;
        self.write(&mut state, head, HeadWriteStage::Publish).await
    }

    async fn write(
        &self,
        state: &mut HeldHead,
        head: ServingHead,
        stage: HeadWriteStage,
    ) -> Result<()> {
        let result = cas_put(
            self.store.as_ref(),
            &self.path,
            &head,
            PutMode::Update(state.expected.clone()),
        )
        .await;
        match result {
            Ok(result) => {
                state.expected = result;
                state.head = head;
                Ok(())
            }
            Err(error) => {
                state.status = HeadStatus::Failed;
                telemetry::head_write_failed(stage, &error);
                Err(WriterError::HeadCasFailed)
            }
        }
    }

    /// Serialize the final conditional deletion with renewal on the same token.
    pub(crate) async fn delete_head(&self, config: &Config) -> Result<()> {
        let mut state = self.state.lock().await;
        self.live(&state)?;
        match fyrr_reader::storage::delete_head_if_match(config, &state.expected).await {
            Ok(()) => {
                state.status = HeadStatus::Deleted;
                Ok(())
            }
            Err(error) => {
                state.status = HeadStatus::Failed;
                Err(match error {
                    object_store::Error::Precondition { .. } => WriterError::HeadCasFailed,
                    object_store::Error::NotSupported { .. } => {
                        WriterError::ConditionalDeleteUnsupported
                    }
                    _ => WriterError::StorageUnavailable,
                })
            }
        }
    }

    pub(crate) fn keepalive(self: &Arc<Self>) -> Renewal {
        let guard = self.clone();
        Renewal::spawn(guard.ttl / 3, move || {
            let guard = guard.clone();
            async move {
                let mut state = guard.state.lock().await;
                if state.status == HeadStatus::Deleted {
                    return false;
                }
                if guard.live(&state).is_err() {
                    state.status = HeadStatus::Failed;
                    return false;
                }
                let mut head = state.head.clone();
                if let Some(lease) = &mut head.lease {
                    lease.expires_at = fyrr_core::clock::now()
                        + chrono::Duration::from_std(guard.ttl)
                            .unwrap_or_else(|_| unreachable!("acquisition validated the TTL"));
                }
                if guard
                    .write(&mut state, head, HeadWriteStage::Renew)
                    .await
                    .is_err()
                {
                    return false;
                }
                state.renewed = Instant::now();
                true
            }
        })
    }

    pub async fn release(&self) -> Result<()> {
        let mut state = self.state.lock().await;
        if state.status == HeadStatus::Deleted {
            return Ok(());
        }
        // A publication response may have been lost. Read the S3 authority
        // before release and preserve every pointer it actually published.
        let object = self.store.get(&self.path).await?;
        let expected = version_of(&object.meta);
        let mut head: ServingHead =
            parse_contract(&object.bytes().await?).map_err(|_| WriterError::PublicationInvalid)?;
        if head
            .lease
            .as_ref()
            .is_none_or(|l| l.holder != self.lease.holder || l.epoch != self.lease.epoch)
        {
            return Err(WriterError::LeaseLost);
        }
        state.expected = expected;
        // Retain the epoch after release so the next holder cannot reuse it.
        if let Some(lease) = &mut head.lease {
            lease.expires_at = fyrr_core::clock::now();
        }
        self.write(&mut state, head, HeadWriteStage::Release).await
    }
}

